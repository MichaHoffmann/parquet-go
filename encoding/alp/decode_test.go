func TestDecodeFloatGolden(t *testing.T) {
	// Values [10, 11, 12, 13], exponent=0, factor=0, FOR=10, and deltas
	// 0,1,2,3 packed at bit width 2.
	page := []byte{
		0x00, 0x00, 0x0a,
		0x04, 0x00, 0x00, 0x00,
		0x04, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00,
		0x0a, 0x00, 0x00, 0x00,
		0x02,
		0xe4,
	}
	var e alp.Encoding
	got, err := e.DecodeFloat(nil, page)
	if err != nil {
		t.Fatalf("decode: %v", err)
	}
	want := []float32{10, 11, 12, 13}
	if len(got) != len(want) {
		t.Fatalf("length: got %d want %d", len(got), len(want))
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("value %d: got %v want %v", i, got[i], want[i])
		}
	}
}

