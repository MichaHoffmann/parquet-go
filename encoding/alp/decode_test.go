func assertDoubleBits(t *testing.T, page []byte, wantBits []uint64) {
	t.Helper()
	var e alp.Encoding
	got, err := e.DecodeDouble(nil, page)
	if err != nil {
		t.Fatalf("decode: %v", err)
	}
	if len(got) != len(wantBits) {
		t.Fatalf("length: got %d want %d", len(got), len(wantBits))
	}
	for i := range wantBits {
		if math.Float64bits(got[i]) != wantBits[i] {
			t.Fatalf("value %d: got bits %#016x (%v) want %#016x", i, math.Float64bits(got[i]), got[i], wantBits[i])
		}
	}
}

